clear; clc; close all;

% Параметры задачи
% y'' - 0.5xy' + y = 2
% 2y(0.4) - y'(0.4) = 4.2742
% y(3) = 2
% Отрезок [0.4, 3]

a = 0.4; b = 3;
n = 100; % Количество отрезков
h = (b - a) / n;
x = a:h:b;
N = n + 1; % Количество узлов

% --- ПУНКТ 1: Подготовка (вычисление диагоналей и правой части) ---
diag1 = zeros(1, N); % Нижняя диагональ (при y_{i-1})
diag2 = zeros(1, N); % Главная диагональ (при y_{i})
diag3 = zeros(1, N); % Верхняя диагональ (при y_{i+1})
F = zeros(1, N);     % Вектор правой части

% Заполнение для внутренних точек i = 2 ... N-1
for i = 2:N-1
    xi = x(i);
    % Используем формулы МКР:
    diag1(i) = 1/h^2 + (0.5*xi)/(2*h);
    diag2(i) = 1 - 2/h^2;
    diag3(i) = 1/h^2 - (0.5*xi)/(2*h);
    F(i) = 2;
end

% Краевое условие слева (x=0.4): 2y - y' = 4.2742
% 2*y1 - (y2 - y1)/h = 4.2742  => y1*(2 + 1/h) + y2*(-1/h) = 4.2742
diag1(1) = 0;
diag2(1) = 2 + 1/h;
diag3(1) = -1/h;
F(1) = 4.2742;

% Краевое условие справа (x=3): y = 2
diag1(N) = 0;
diag2(N) = 1;
diag3(N) = 0;
F(N) = 2;

% --- ПУНКТ 2: Формирование матрицы для наглядности ---
M = diag(diag2) + diag(diag1(2:N), -1) + diag(diag3(1:N-1), 1);
fprintf('Фрагмент матрицы системы (верхний угол):\n');
disp(M(1:4, 1:4));

% --- ПУНКТ 3: Метод прогонки ---
P = zeros(1, N);
Q = zeros(1, N);

% Прямой ход (вычисление прогоночных коэффициентов)
P(1) = -diag3(1) / diag2(1);
Q(1) = F(1) / diag2(1);

for i = 2:N
    denom = diag2(i) + diag1(i) * P(i-1);
    if i < N
        P(i) = -diag3(i) / denom;
    end
    Q(i) = (F(i) - diag1(i) * Q(i-1)) / denom;
end

% Обратный ход (нахождение y)
y = zeros(1, N);
y(N) = Q(N);
for i = N-1:-1:1
    y(i) = P(i) * y(i+1) + Q(i);
end

% --- ПУНКТ 4: График ---
figure('Color', 'w');
plot(x, y, 'r-', 'LineWidth', 2, 'DisplayName', 'Численное решение');
hold on; grid on;

% Точки на краях
plot(x(1), y(1), 'bo', 'MarkerFaceColor', 'b', 'DisplayName', 'Левая граница');
plot(x(end), y(end), 'go', 'MarkerFaceColor', 'g', 'DisplayName', 'Правая граница');

xlabel('x'); ylabel('y(x)');
title('Решение краевой задачи методом прогонки');
legend('Location', 'best');

% Проверка (вывод в консоль)
fprintf('Проверка: y(3) = %.4f (должно быть 2.0000)\n', y(end));