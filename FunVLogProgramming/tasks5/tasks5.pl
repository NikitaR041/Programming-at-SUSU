%20. Заменить все буквы в атоме A равные X на Y.
 %  ?-замена('азбука','а','б',R).
 %  R=бзбукб
 
замена(A, X, Y, R) :- atom_chars(A, L), замена_букв(L, X, Y, NewL), atom_chars(R, NewL).

замена_букв([], _, _, []).
замена_букв([X|T], X, Y, [Y|NewT]) :- !, замена_букв(T, X, Y, NewT).
замена_букв([H|T], X, Y, [H|NewT]) :- замена_букв(T, X, Y, NewT).

