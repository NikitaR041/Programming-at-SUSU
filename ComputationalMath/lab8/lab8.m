function x = lab8(A, b)
    % Решение системы линейных уравнений методом Холецкого
    % Входные параметры:
    %   A - симметричная положительно определенная матрица (n x n)
    %   b - вектор правой части (n x 1)
    % Выходные параметры:
    %   x - решение системы (n x 1)
    
    n = length(b);
    U = zeros(n,n);
    
    % Разложение Холецкого: A = U' * U
    for i = 1:n
        % Диагональный элемент
        U(i,i) = sqrt(A(i,i) - sum(U(1:i-1,i).^2));
        
        % Внедиагональные элементы
        for j = i+1:n
            U(i,j) = (A(i,j) - U(1:i-1,i)' * U(1:i-1,j)) / U(i,i);
        end
    end
    
    % Решение U' * y = b (прямой ход)
    y = zeros(n,1);
    for i = 1:n
        y(i) = (b(i) - U(1:i-1,i)' * y(1:i-1)) / U(i,i);
    end
    
    % Решение U * x = y (обратный ход)
    x = zeros(n,1);
    for i = n:-1:1
        x(i) = (y(i) - U(i,i+1:n) * x(i+1:n)) / U(i,i);
    end
end