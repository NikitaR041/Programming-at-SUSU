A = [6  2  1  0;
     2  5 -1  1;
     1 -1  4  2;
     0  1  2  5];

% Зададим известное целое решение:
x_true = [1; 2; 3; 4];

% Вычислим правую часть:
b = A * x_true;

% ---------------------------------------------------------------
% Решаем систему методом квадратных корней (Холецкого)
% ---------------------------------------------------------------
tic;
x_cholesky = lab8(A, b);
t_cholesky = toc;

% Решаем методом Гаусса для проверки
tic;
x_gauss = A \ b;
t_gauss = toc;

% ---------------------------------------------------------------
% Вывод результатов
% ---------------------------------------------------------------
disp('Матрица A:');
disp(A);

disp('Правая часть b:');
disp(b);

disp('Решение методом Холецкого:');
disp(x_cholesky');

disp('Решение методом Гаусса (A\\b):');
disp(x_gauss');

fprintf('Погрешность между методами: %.2e\n', norm(x_cholesky - x_gauss));
fprintf('Время метода квадратных корней: %.6f секунд\n', t_cholesky);
fprintf('Время метода Гаусса:            %.6f секунд\n', t_gauss);

