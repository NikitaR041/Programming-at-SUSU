% Испытательная программа для метода Холецкого
clear; clc;

fprintf('МЕТОД ХОЛЕЦКОГО ДЛЯ РЕШЕНИЯ СЛАУ\n');
fprintf('=================================\n\n');

% Испытательная система 1 - целочисленная матрица и решение
A = [4,  2,  0,  0;
     2,  5,  2,  0;
     0,  2,  5,  2;
     0,  0,  2,  4];

b = [8; 18; 27; 22];
expected_x = [1; 2; 3; 4];

fprintf('Матрица A:\n');
disp(A);
fprintf('Вектор b:\n');
disp(b);
fprintf('Ожидаемое решение:\n');
disp(expected_x);

% Проверка положительной определенности
fprintf('\nПРОВЕРКА ПОЛОЖИТЕЛЬНОЙ ОПРЕДЕЛЕННОСТИ:\n');
fprintf('Главные миноры: %.4f, %.4f, %.4f, %.4f\n', ...
    det(A(1,1)), det(A(1:2,1:2)), det(A(1:3,1:3)), det(A));
fprintf('Собственные значения: ');
eig_vals = eig(A);
fprintf('%.4f ', eig_vals);
fprintf('\n');

% Решение методом Холецкого
fprintf('\nРЕШЕНИЕ МЕТОДОМ ХОЛЕЦКОГО:\n');
x_cholesky = lab8(A, b);
fprintf('Решение: [%.6f, %.6f, %.6f, %.6f]ᵀ\n', x_cholesky);

% Решение методом Гаусса (встроенный оператор)
fprintf('\nРЕШЕНИЕ МЕТОДОМ ГАУССА (A\\b):\n');
x_gauss = A \ b;
fprintf('Решение: [%.6f, %.6f, %.6f, %.6f]ᵀ\n', x_gauss);

% Проверка разложения Холецкого
fprintf('\nПРОВЕРКА РАЗЛОЖЕНИЯ ХОЛЕЦКОГО:\n');
try
    U_chol = chol(A);
    fprintf('Встроенная функция chol успешно выполнена\n');
    fprintf('Норма разности: ||A - Uᵀ*U|| = %.2e\n', norm(A - U_chol' * U_chol));
catch
    fprintf('Матрица не является положительно определенной для chol\n');
end

% Сравнение результатов
fprintf('\nСРАВНЕНИЕ РЕЗУЛЬТАТОВ:\n');
fprintf('Норма разности с ожидаемым решением: %.2e\n', norm(x_cholesky - expected_x));
fprintf('Норма разности между методами: %.2e\n', norm(x_cholesky - x_gauss));
fprintf('||A*x - b|| = %.2e\n', norm(A * x_cholesky - b));

% Проверка на другой системе
fprintf('\nДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА:\n');
fprintf('========================\n');

% Вторая симметричная положительно определенная матрица с целочисленным решением
A2 = [5, 1, 1, 1;
      1, 5, 1, 1;
      1, 1, 5, 1;
      1, 1, 1, 5];
b2 = [14; 18; 22; 26];
expected_x2 = [1; 2; 3; 4];

fprintf('Матрица A2:\n');
disp(A2);
fprintf('Вектор b2:\n');
disp(b2);
fprintf('Ожидаемое решение:\n');
disp(expected_x2);

x2_cholesky = lab8(A2, b2);
x2_gauss = A2 \ b2;

fprintf('Решение методом Холецкого: [%.6f, %.6f, %.6f, %.6f]ᵀ\n', x2_cholesky);
fprintf('Решение методом Гаусса:    [%.6f, %.6f, %.6f, %.6f]ᵀ\n', x2_gauss);
fprintf('Норма разности с ожидаемым решением: %.2e\n', norm(x2_cholesky - expected_x2));
fprintf('Норма разности между методами: %.2e\n', norm(x2_cholesky - x2_gauss));
fprintf('||A2*x - b2|| = %.2e\n', norm(A2 * x2_cholesky - b2));

% Третья проверка - матрица большего размера
fprintf('\nПРОВЕРКА НА МАТРИЦЕ 5-ГО ПОРЯДКА:\n');
fprintf('=================================\n');

A3 = [6, 1, 1, 1, 1;
      1, 6, 1, 1, 1;
      1, 1, 6, 1, 1;
      1, 1, 1, 6, 1;
      1, 1, 1, 1, 6];
b3 = [10; 14; 18; 22; 26];
expected_x3 = [1; 2; 3; 4; 5];

fprintf('Матрица A3 (5x5):\n');
disp(A3);
fprintf('Вектор b3:\n');
disp(b3);

x3_cholesky = lab8(A3, b3);
x3_gauss = A3 \ b3;

fprintf('Решение методом Холецкого: [%.6f, %.6f, %.6f, %.6f, %.6f]ᵀ\n', x3_cholesky);
fprintf('Решение методом Гаусса:    [%.6f, %.6f, %.6f, %.6f, %.6f]ᵀ\n', x3_gauss);
fprintf('Норма разности с ожидаемым решением: %.2e\n', norm(x3_cholesky - expected_x3));
fprintf('Норма разности между методами: %.2e\n', norm(x3_cholesky - x3_gauss));
fprintf('||A3*x - b3|| = %.2e\n', norm(A3 * x3_cholesky - b3));
