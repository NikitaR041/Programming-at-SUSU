function x = lab7(a, b, c, d)
% =========================================================================
% Назначение:
%   Решение системы линейных алгебраических уравнений (СЛАУ) трёхдиагонального
%   вида методом прогонки (методом Томаса).
%
% Входные параметры:
%   a — поддиагональ матрицы (вектор длиной n-1)
%   b — главная диагональ матрицы (вектор длиной n)
%   c — наддиагональ матрицы (вектор длиной n-1)
%   d — правая часть системы (вектор длиной n)
%
% Выходной параметр:
%   x — решение системы (вектор длиной n)
%
% Уравнение системы имеет вид:
%   a_i * x_(i-1) + b_i * x_i + c_i * x_(i+1) = d_i,  i = 1..n
%
% =========================================================================
    n = length(b);
    alpha = zeros(1, n);
    beta  = zeros(1, n);
    
    % ---- Прямая прогонка ----
    alpha(1) = -c(1) / b(1);
    beta(1)  =  d(1) / b(1);
    
    for i = 2:n-1
        mu = b(i) + a(i-1)*alpha(i-1); 
        alpha(i) = -c(i) / mu;
        beta(i)  = (d(i) - a(i-1)*beta(i-1)) / mu;
    end
    
    % Последний элемент
    x = zeros(1, n);
    x(n) = (d(n) - a(n-1)*beta(n-1)) / (b(n) + a(n-1)*alpha(n-1));
    
    % ---- Обратная прогонка ----
    for i = n-1:-1:1
        x(i) = alpha(i)*x(i+1) + beta(i);
    end
end